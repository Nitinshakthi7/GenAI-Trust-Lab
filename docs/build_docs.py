def pipeline(slide, x, accent, text_col, light, header, steps, side_text, y_first, y_last,
             box_w, box_h, side_h):
    """One pipeline column: a header, stacked step boxes joined by arrows, and a side chip
    that feeds into the LAST step box."""
    colw = (CW - 0.35) / 2
    card(slide, x, 1.5, colw, 4.45, accent, fill=light)
    add_text(slide, x + 0.32, 1.6, colw - 0.5, 0.35, [P(R(header, 14, text_col, bold=True))], MSO_ANCHOR.MIDDLE)
    n = len(steps)
    step = (y_last - y_first) / (n - 1)
    boxes = []
    for i, text in enumerate(steps):
        b = box(slide, x + 0.35, y_first + i * step, box_w, box_h, [
            P(R(f"{i + 1}  ", 14, text_col, bold=True), R(text, 14, NAVY)),
        ], fill=WHITE, line=BORDER, radius=0.15, margins=(0.15, 0.03, 0.1, 0.03))
        boxes.append(b)
    for a, b in zip(boxes, boxes[1:]):
        arrow(slide, a, 2, b, 0)
    # Side chip next to the last step box, with an arrow pointing into it.
    chip_x = x + 0.35 + box_w + 0.4
    chip_w = colw - (0.35 + box_w + 0.4) - 0.2
    last_y = y_first + (n - 1) * step
    chip = box(slide, chip_x, last_y + box_h / 2 - side_h / 2, chip_w, side_h,
               [P(R(line, 12, NAVY), align=PP_ALIGN.CENTER) for line in side_text.split("\n")],
               fill=WHITE, line=accent, line_pt=1.5, radius=0.2, margins=(0.05, 0.03, 0.05, 0.03))
    arrow(slide, chip, 1, boxes[-1], 3)


