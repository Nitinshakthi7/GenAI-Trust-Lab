# --- Tiny text helpers ---------------------------------------------
# R() describes one run of text. P() describes one paragraph made of runs.
def R(text, size=14, color=NAVY, bold=False, font=BODY_FONT, italic=False):
    return dict(text=text, size=size, color=color, bold=bold, font=font, italic=italic)


def P(*runs, align=PP_ALIGN.LEFT, after=0, before=0):
    return dict(runs=list(runs), align=align, after=after, before=before)


def write(tf, paras, anchor=MSO_ANCHOR.TOP, margins=(0.0, 0.0, 0.0, 0.0), frame=True):
    """Write paragraphs into a text frame. Wrapping is on, auto-fit is OFF.
    margins = (left, top, right, bottom) in inches. frame=False is used for table cells."""
    if frame:
        tf.word_wrap = True
        tf.auto_size = MSO_AUTO_SIZE.NONE
        tf.vertical_anchor = anchor
        tf.margin_left, tf.margin_top, tf.margin_right, tf.margin_bottom = [Inches(m) for m in margins]
    for i, p in enumerate(paras):
        para = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        para.alignment = p["align"]
        para.space_after = Pt(p["after"])
        para.space_before = Pt(p["before"])
        for r in p["runs"]:
            run = para.add_run()
            run.text = r["text"]
            font = run.font
            font.name = r["font"]
            font.size = Pt(r["size"])
            font.bold = r["bold"]
            font.italic = r["italic"]
            font.color.rgb = rgb(r["color"])


def add_text(slide, x, y, w, h, paras, anchor=MSO_ANCHOR.TOP):
    """A plain text box (no fill, no outline)."""
    box_ = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    write(box_.text_frame, paras, anchor)
    return box_


def box(slide, x, y, w, h, paras=None, fill=CARD, line=BORDER, line_pt=0.75,
        shape=MSO_SHAPE.ROUNDED_RECTANGLE, radius=0.12, anchor=MSO_ANCHOR.MIDDLE,
        margins=(0.12, 0.05, 0.12, 0.05)):
    """A filled shape (card, chip, step box) with optional text inside."""
    s = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    if shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        s.adjustments[0] = radius          # corner roundness (fraction of the shorter side)
    s.fill.solid()
    s.fill.fore_color.rgb = rgb(fill)
    if line:
        s.line.color.rgb = rgb(line)
        s.line.width = Pt(line_pt)
    else:
        s.line.fill.background()
    s.shadow.inherit = False               # no theme shadow: flat, clean look
    if paras:
        write(s.text_frame, paras, anchor, margins)
    return s


def card(slide, x, y, w, h, accent, fill=CARD, paras=None, anchor=MSO_ANCHOR.TOP,
         margins=(0.32, 0.14, 0.2, 0.1)):
    """A light rounded card with a thin accent bar on its left edge."""
    c = box(slide, x, y, w, h, paras, fill=fill, radius=0.05, anchor=anchor, margins=margins)
    box(slide, x, y + 0.14, 0.08, h - 0.28, fill=accent, line=None, shape=MSO_SHAPE.RECTANGLE)
    return c


def arrow(slide, from_shape, from_site, to_shape, to_site, color=GREY, width_pt=1.75):
    """A real connector glued to two shapes, with an arrowhead at the end.
    Connection sites on a rectangle: 0 = top, 1 = left, 2 = bottom, 3 = right."""
    c = slide.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, 0, 0, 0, 0)
    c.begin_connect(from_shape, from_site)
    c.end_connect(to_shape, to_site)
    c.line.color.rgb = rgb(color)
    c.line.width = Pt(width_pt)
    ln = c.line._get_or_add_ln()
    tail = etree.SubElement(ln, qn("a:tailEnd"))   # arrowhead at the end of the line
    tail.set("type", "triangle")
    tail.set("w", "med")
    tail.set("len", "med")
    return c


