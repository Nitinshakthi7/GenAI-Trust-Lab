def docx_set_style_font(style, size, color=None, bold=None):
    """Give a Word style our font, size and colour (also removes theme-font overrides)."""
    style.font.name = DOCX_FONT
    style.font.size = DPt(size)
    if color is not None:
        style.font.color.rgb = color
    if bold is not None:
        style.font.bold = bold
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.find(docx_qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        rfonts.set(docx_qn(attr), DOCX_FONT)
    # Theme attributes would override the font name above, so remove them.
    for attr in ("w:asciiTheme", "w:hAnsiTheme", "w:eastAsiaTheme", "w:cstheme"):
        if rfonts.get(docx_qn(attr)) is not None:
            del rfonts.attrib[docx_qn(attr)]


def docx_shade(cell, hex_fill):
    """Fill a table cell with a background colour."""
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(docx_qn("w:val"), "clear")
    shd.set(docx_qn("w:color"), "auto")
    shd.set(docx_qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def docx_cell_text(cell, text, bold=False, color=None, size=10):
    """Write text into a table cell with our font and size."""
    cell.text = ""
    para = cell.paragraphs[0]
    para.paragraph_format.space_after = DPt(2)
    para.paragraph_format.space_before = DPt(2)
    run = para.add_run(text)
    run.font.name = DOCX_FONT
    run.font.size = DPt(size)
    run.bold = bold
    if color is not None:
        run.font.color.rgb = color


def docx_add_table(doc, caption, header, rows, widths):
    """Add a captioned table: navy header row, light grid, fixed column widths."""
    if caption:
        cap = doc.add_paragraph()
        cap.paragraph_format.space_before = DPt(6)
        cap.paragraph_format.space_after = DPt(3)
        cap.paragraph_format.keep_with_next = True
        run = cap.add_run(caption)
        run.bold = True
        run.font.size = DPt(10.5)
        run.font.color.rgb = GREY_RGB
    table = doc.add_table(rows=1, cols=len(header))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.LEFT
    table.autofit = False
    for i, text in enumerate(header):
        cell = table.rows[0].cells[i]
        docx_cell_text(cell, text, bold=True, color=DRGB(0xFF, 0xFF, 0xFF))
        docx_shade(cell, "1E293B")
    for row in rows:
        cells = table.add_row().cells
        for i, text in enumerate(row):
            docx_cell_text(cells[i], text, bold=(i == 0))
    for row in table.rows:
        for i, width in enumerate(widths):
            row.cells[i].width = DInches(width)
    doc.add_paragraph().paragraph_format.space_after = DPt(2)


