def cell_borders(cell, color=BORDER, width_pt=0.75):
    """Thin light border on all four sides of a table cell (python-pptx has no API for this)."""
    tc_pr = cell._tc.get_or_add_tcPr()
    for tag in ("a:lnL", "a:lnR", "a:lnT", "a:lnB"):
        ln = etree.SubElement(tc_pr, qn(tag))
        ln.set("w", str(int(width_pt * 12700)))
        ln.set("cap", "flat")
        ln.set("cmpd", "sng")
        ln.set("algn", "ctr")
        fill = etree.SubElement(ln, qn("a:solidFill"))
        etree.SubElement(fill, qn("a:srgbClr")).set("val", color)
        etree.SubElement(ln, qn("a:prstDash")).set("val", "solid")


def add_table(slide, x, y, col_widths, row_h, header, rows, size=12):
    """An empty-looking results table with a navy header row."""
    gf = slide.shapes.add_table(len(rows) + 1, len(header), Inches(x), Inches(y),
                                Inches(sum(col_widths)), Inches(row_h * (len(rows) + 1)))
    table = gf.table
    # Use the "No Style, No Grid" table style so only our own colours show.
    table._tbl.tblPr.find(qn("a:tableStyleId")).text = "{2D5ABB26-0587-4C30-8999-92F81FD0307C}"
    table.horz_banding = False
    for i, w in enumerate(col_widths):
        table.columns[i].width = Inches(w)
    all_rows = [header] + rows
    for r_idx, row_values in enumerate(all_rows):
        table.rows[r_idx].height = Inches(row_h)
        for c_idx, text in enumerate(row_values):
            cell = table.cell(r_idx, c_idx)
            is_header = r_idx == 0
            cell_borders(cell)
            cell.fill.solid()
            cell.fill.fore_color.rgb = rgb(NAVY if is_header else WHITE)
