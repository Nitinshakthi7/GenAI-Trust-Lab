function useModelResults() {
  const [results, setResults] = useState(null);
  useEffect(() => {
    if (stubMode) return;
    const controller = new AbortController();
    fetch(sitePath('results/model-cards.json'), { signal: controller.signal })
      .then((response) => response.ok ? response.json() : null)
      .then((data) => {
        if (!controller.signal.aborted && data) setResults(data);
      })
      .catch(() => {});
    return () => controller.abort();
  }, []);
  return results;
}

function ModelCards({ results }) {
  return <div className="model-card-grid">
    {modelCards.map(([id, purpose, dataset]) => {
      const model = results?.models?.[id];
      const measurements = model?.script && model?.config ? Object.entries(model.measurements || {}) : [];
      return <article className="lab-panel model-card" key={id}>
        <h3><code>{id}</code></h3>
        <p>{purpose}</p>
        <p className="field-hint">{dataset}</p>
        {measurements.length ? <>
          <dl className="evidence-fields">{measurements.map(([name, value]) => <div key={name}><dt>{name}</dt><dd>{Number.isFinite(value) ? formatNumber(value) : placeholder}</dd></div>)}</dl>
          <p className="field-hint">Source script <code>{model.script}</code></p>
          <p className="field-hint">Run config <code>{model.config}</code></p>
        </> : <p className="field-hint">{placeholder}</p>}
      </article>;
    })}
  </div>;
}

